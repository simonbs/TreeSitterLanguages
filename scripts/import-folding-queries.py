#!/usr/bin/env python3
"""Reproduce standalone folding queries from pinned, attributed upstream inputs.

Normal/check runs are offline. --download refreshes the retained source files from
their pinned URLs and verifies previously recorded SHA-256 hashes.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = ROOT / 'FoldingQueries'
MANIFEST = DIRECTORY / 'sources.json'
INHERITS = re.compile(r'^\s*;+\s*inherits:\s*(.*?)\s*$', re.M)


def digest(content):
    return hashlib.sha256(content).hexdigest()


def source_url(source):
    return 'https://raw.githubusercontent.com/{repository}/{revision}/{path}'.format(**source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--download', action='store_true')
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    sources = manifest['sources']
    texts = {}

    def load(identifier):
        if identifier in texts:
            return texts[identifier]
        source = sources[identifier]
        path = DIRECTORY / 'Upstream' / (identifier + '.scm')
        if arguments.download:
            with urllib.request.urlopen(source_url(source)) as response:
                data = response.read()
            if source.get('sha256') and source['sha256'] != digest(data):
                raise ValueError('Pinned source changed: ' + identifier)
            path.write_bytes(data)
        data = path.read_bytes()
        if source.get('sha256') and source['sha256'] != digest(data):
            raise ValueError('Source checksum mismatch: ' + identifier)
        source['sha256'] = digest(data)
        text = data.decode()
        texts[identifier] = text
        for names in INHERITS.findall(text):
            for name in names.split(','):
                name = name.strip().strip('()')
                parent = 'nvim-' + name
                if parent not in sources:
                    sources[parent] = {
                        'repository': 'nvim-treesitter/nvim-treesitter',
                        'revision': manifest['nvim_revision'],
                        'path': 'runtime/queries/' + name + '/folds.scm',
                        'license': 'Apache-2.0',
                        'notice': 'Licenses/Folding/nvim-treesitter-APACHE-2.0.txt',
                    }
                load(parent)
        return text

    def compose(identifier, visited):
        if identifier in visited:
            return ''
        visited.add(identifier)
        text = load(identifier)
        result = ''
        for names in INHERITS.findall(text):
            for name in names.split(','):
                result += compose('nvim-' + name.strip().strip('()'), visited)
        source = sources[identifier]
        result += '; Source: ' + source_url(source) + '\n'
        result += INHERITS.sub('', text).strip() + '\n\n'
        return result

    count = 0
    for language, identifier in manifest['languages'].items():
        if identifier is None:
            continue
        output = '; Generated by scripts/import-folding-queries.py; see FoldingQueries/sources.json.\n'
        output += '; Modified for Runestone: query inheritance expanded; see manifest for adaptations.\n'
        output += '; Copyright and license notices: Licenses/Folding and existing grammar notices.\n\n'
        output += compose(identifier, set())
        if language == 'Markdown':
            output = re.sub(r'(?m)^\s*\(section\)\s*\n', '', output)
            output += '; Runestone extension: derive sections from both heading styles.\n'
            output += '[(atx_heading) (setext_heading)] @fold.heading\n'
        path = ROOT / 'Sources' / ('TreeSitter' + language + 'Queries') / 'folds.scm'
        if arguments.check:
            if path.read_text() != output:
                raise ValueError('Generated query differs: ' + str(path))
        else:
            path.write_text(output)
        count += 1
    if not arguments.check:
        MANIFEST.write_text(json.dumps(manifest, indent=2, sort_keys=True) + '\n')
    print('Folding queries: ' + ('verified' if arguments.check else 'generated') + f' {count} languages from {len(sources)} pinned source files')


if __name__ == '__main__':
    main()
